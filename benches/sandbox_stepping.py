"""Agent sandbox: `session` versus `replay` stepping on one long episode.

A scripted quoting agent (one buy at the best bid and one sell at the best ask kept working, re-quoted when the touch
moves away, everything cancelled and re-sent every `--requote` steps) trades the synthetic fixture day
(`tests/fixtures/synth_small`, instrument 1, 2026-06-15) in steps of `--step` from the open, for each episode length
in `--steps`. Both steppings run the same episode `--repeats` times (interleaved); the script checks that every run
commits the same log (root) and the same scorecard (`scorecard_sha256`), and prints one JSON line per (length,
stepping) with the median wall times (open, steps, `finish`, total) and the per-run totals. No real market data: the
fixture is generated by the project's own code.

    uv run --frozen --no-sync python benches/sandbox_stepping.py --steps 250 500 1000 2000 4000 --repeats 3
"""

from __future__ import annotations

import argparse
import json
import statistics
import time
from pathlib import Path
from typing import Any

from queuetruth.sandbox import Sandbox

REPO = Path(__file__).resolve().parents[1]
SPEC = {
    "dataset": {"path": str(REPO / "tests" / "fixtures" / "synth_small")},
    "instrument_id": 1,
    "session_date": "2026-06-15",
    "latency": "250us",
    "jitter": "100us",
    "seed": 1,
    "max_steps": 1_000_000,
    "max_open_orders": 64,
}


def episode(steps: int, step: str, requote: int, stepping: str) -> dict[str, Any]:
    t0 = time.perf_counter()
    sb = Sandbox.open(SPEC, stepping=stepping)
    opened = time.perf_counter() - t0
    obs = sb.observe()
    sent = 0
    t1 = time.perf_counter()
    for k in range(steps):
        if obs.done:
            break
        working = {o.side: o for o in obs.orders if o.status in ("pending", "working")}
        for side, best in (("buy", obs.book.bid), ("sell", obs.book.ask)):
            o = working.get(side)
            stale = o is not None and best is not None and o.price != best[0]
            if o is not None and (stale or k % requote == 0) and o.status == "working" and o.cancel_sent_ns is None:
                sb.cancel(o.order_id)
                o = None
            if o is None and best is not None:
                sb.submit(side, 1, price=best[0])
                sent += 1
        obs = sb.advance(by=step)
    stepped = time.perf_counter() - t1
    t2 = time.perf_counter()
    card = sb.finish()
    finished = time.perf_counter() - t2
    return {
        "stepping": stepping,
        "steps": sb.step,
        "orders": sent,
        "fills": len(card.fills),
        "open_s": round(opened, 3),
        "steps_s": round(stepped, 3),
        "finish_s": round(finished, 3),
        "total_s": round(opened + stepped + finished, 3),
        "log_root": sb.order_log()["root"],
        "scorecard_sha256": card.certificate.scorecard_sha256,
        "consistent": card.consistency.equal,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--steps", type=int, nargs="+", default=[250, 500, 1000, 2000])
    ap.add_argument("--step", default="5s")
    ap.add_argument("--requote", type=int, default=20)
    ap.add_argument("--repeats", type=int, default=3, help="runs per (length, stepping); medians are reported")
    ap.add_argument("--max-replay-steps", type=int, default=10**9, help="skip replay stepping above this length")
    a = ap.parse_args()
    for n in a.steps:
        modes = ["session", "replay"] if n <= a.max_replay_steps else ["session"]
        runs: dict[str, list[dict[str, Any]]] = {m: [] for m in modes}
        for _ in range(a.repeats):
            for m in modes:
                runs[m].append(episode(n, a.step, a.requote, m))
        ids = {(r["log_root"], r["scorecard_sha256"]) for rs in runs.values() for r in rs}
        if len(ids) != 1:
            raise SystemExit(f"{n} steps: the runs differ")
        med: dict[str, dict[str, Any]] = {}
        for m, rs in runs.items():
            med[m] = {
                **{k: rs[0][k] for k in ("stepping", "steps", "orders", "fills", "log_root", "scorecard_sha256")},
                **{
                    k: round(statistics.median(r[k] for r in rs), 3)
                    for k in ("open_s", "steps_s", "finish_s", "total_s")
                },
                "ms_per_step": round(1000 * statistics.median(r["steps_s"] for r in rs) / max(1, rs[0]["steps"]), 2),
                "totals_s": [r["total_s"] for r in rs],
                "consistent": all(r["consistent"] for r in rs),
            }
            print(json.dumps({"requested_steps": n, "repeats": a.repeats, **med[m]}), flush=True)
        if len(med) == 2:
            speedup = med["replay"]["total_s"] / med["session"]["total_s"]
            print(json.dumps({"requested_steps": n, "speedup_median": round(speedup, 1)}), flush=True)


if __name__ == "__main__":
    main()
