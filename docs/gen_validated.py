"""Generate the "What is validated" page and the README status block from docs/validated.toml.

Usage:
    uv run --frozen --no-sync python docs/gen_validated.py [--check]

Writes docs/validated.md and the block between `<!-- validated:start -->` and `<!-- validated:end -->` in README.md.
With --check, writes nothing and exits 1 when either is out of date. docs/check_docs.py runs the check.
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "docs" / "validated.toml"
PAGE = ROOT / "docs" / "validated.md"
README = ROOT / "README.md"
START, END = "<!-- validated:start -->", "<!-- validated:end -->"
#: The published docs site (.github/workflows/atlas.yml builds it); the README links pages there.
SITE = "https://sarptandoven.github.io/queuetruth/docs/"

STATUS = {
    "real_data": "Validated on real data",
    "real_library": "Checked against the library",
    "documented": "From public documentation only",
    "fixtures_only": "Fixtures and synthetic data only",
}
ORDER = list(STATUS)


def load() -> list[dict]:
    rows = tomllib.loads(DATA.read_text(encoding="utf-8"))["row"]
    for r in rows:
        if r["status"] not in STATUS:
            raise SystemExit(f"{DATA.name}: unknown status {r['status']!r} in row {r['area']!r}")
    return sorted(rows, key=lambda r: ORDER.index(r["status"]))


def page(rows: list[dict]) -> str:
    out = [
        "# What is validated",
        "",
        "<!-- Generated by docs/gen_validated.py from docs/validated.toml. Do not edit by hand. -->",
        "",
        "This is the one table of what queuetruth has checked, and on what. Every other page links here instead of",
        "keeping its own list. A claim is only as strong as its row: real data means real public market files,",
        "fixtures mean files written from public format documents, not real exports.",
        "",
    ]
    for status in ORDER:
        group = [r for r in rows if r["status"] == status]
        if not group:
            continue
        out += [f"## {STATUS[status]}", "", "| Area | What was checked | Evidence |", "|---|---|---|"]
        for r in group:
            ev = ", ".join(f"[{t}]({u})" for t, u in r["evidence"])
            detail = " ".join(r["detail"].split())
            out.append(f"| {r['area']} | {detail} | {ev} |")
        out.append("")
    out += [
        "Exact truth covers displayed liquidity on FIFO venues. It does not model your own order's impact on others,",
        "hidden or iceberg liquidity, auctions or pro-rata matching. How each check runs:",
        "[How queuetruth is tested](testing.md).",
        "",
    ]
    return "\n".join(out)


def readme_block(rows: list[dict]) -> str:
    out = [START, "", "| Area | Status |", "|---|---|"]
    for r in rows:
        out.append(f"| {r['short']} | {STATUS[r['status']]} |")
    out += ["", f"Details and evidence for every row: [What is validated]({SITE}validated/).", "", END]
    return "\n".join(out)


def new_readme(rows: list[dict]) -> str:
    text = README.read_text(encoding="utf-8")
    a, b = text.find(START), text.find(END)
    if a < 0 or b < a:
        raise SystemExit(f"README.md: missing {START} ... {END}")
    return text[:a] + readme_block(rows) + text[b + len(END) :]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when an output is stale; write nothing")
    a = ap.parse_args(argv)
    rows = load()
    want = {PAGE: page(rows), README: new_readme(rows)}
    stale = [p for p, t in want.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
    if a.check:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is stale; run `python docs/gen_validated.py`")
        return 1 if stale else 0
    for p in stale:
        p.write_text(want[p], encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
