"""Docs check: links, runnable code blocks, style and generated references.

Usage:
    uv run --frozen --no-sync python docs/check_docs.py [--page docs/x.md ...] [--no-run] [--require-core]

Checks, over every Markdown file under docs/ (and examples/README.md):

1. Relative links resolve to an existing file or directory; `#anchor` parts match a heading of the target page
   (GitHub slug rules). External links are not fetched.
2. Fenced blocks preceded by `<!-- check-docs: run -->` (optionally `run exit=N`) are executed in order, one fresh
   temporary directory per page, each block in its own process: `sh`/`bash`/`console` blocks with
   `bash -euo pipefail`, `python` blocks with the current interpreter. The environment has the venv's `bin/` first on
   PATH, `QT_SRC` = repo root and `QT_FIXTURES` = `tests/fixtures`. Shell variables do not carry between blocks.
   A runnable block must not contain a `{{PLACEHOLDER}}`.
3. Blocks preceded by `<!-- check-docs: skip (reason) -->` are syntax-checked only (`bash -n`, `ast.parse`), with
   placeholders replaced by `1`.
4. No em-dash or en-dash characters in docs/ and examples/.
5. Every page named in docs/mkdocs.yml `nav` exists, and every page outside docs/launch/ is in the nav.
6. docs/reference/*.md generated by docs/gen_reference.py are current (`gen_reference.py --check`).

Runnable blocks and the generated-reference check need the compiled extension (`queuetruth._core`, `make develop`);
without it they are skipped with a reason unless `--require-core` is given. Exit 0 when every check passed, 1
otherwise.
"""

from __future__ import annotations

import argparse
import ast
import os
import re
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
EXAMPLES = ROOT / "examples"
MARKER = re.compile(r"^\s*<!--\s*check-docs:\s*(run|skip)\b(.*?)-->\s*$")
FENCE = re.compile(r"^(\s*)(`{3,}|~{3,})\s*([\w+-]*)")
LINK = re.compile(r"(?<!!)\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
IMAGE = re.compile(r"!\[[^\]]*\]\(([^)\s]+)\)")
PLACEHOLDER = re.compile(r"\{\{[^{}]+\}\}")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
DASHES = {chr(0x2014): "em-dash", chr(0x2013): "en-dash"}
SHELL = {"sh", "bash", "console", "shell", "zsh"}
BLOCK_TIMEOUT_S = 600


@dataclass
class Block:
    """One fenced code block and its check-docs marker."""

    page: Path
    line: int
    lang: str
    code: str
    mode: str | None = None  # "run", "skip" or None
    arg: str = ""


@dataclass
class Result:
    """Accumulated failures, skips and passes."""

    failures: list[str] = field(default_factory=list)
    skips: list[str] = field(default_factory=list)
    passed: int = 0

    def fail(self, msg: str) -> None:
        self.failures.append(msg)
        print(f"FAIL {msg}", flush=True)

    def skip(self, msg: str) -> None:
        self.skips.append(msg)
        print(f"SKIP {msg}", flush=True)

    def ok(self, msg: str) -> None:
        self.passed += 1
        print(f"ok   {msg}", flush=True)


def rel(p: Path) -> str:
    try:
        return str(p.relative_to(ROOT))
    except ValueError:
        return str(p)


def parse_blocks(page: Path) -> list[Block]:
    """Fenced blocks of a page with the marker on the closest preceding non-blank line."""
    lines = page.read_text(encoding="utf-8").splitlines()
    blocks: list[Block] = []
    i = 0
    while i < len(lines):
        m = FENCE.match(lines[i])
        if not m:
            i += 1
            continue
        fence, lang = m.group(2), m.group(3).lower()
        start = i
        body: list[str] = []
        i += 1
        while i < len(lines) and not lines[i].strip().startswith(fence):
            body.append(lines[i])
            i += 1
        j = start - 1
        while j >= 0 and not lines[j].strip():
            j -= 1
        mode, arg = None, ""
        if j >= 0:
            mk = MARKER.match(lines[j])
            if mk:
                mode, arg = mk.group(1), mk.group(2).strip()
        blocks.append(Block(page, start + 1, lang, "\n".join(body) + "\n", mode, arg))
        i += 1
    return blocks


def slug(text: str) -> str:
    """GitHub heading anchor."""
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = text.strip().lower()
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def anchors(page: Path) -> set[str]:
    out: set[str] = set()
    counts: dict[str, int] = {}
    in_fence = False
    for line in page.read_text(encoding="utf-8").splitlines():
        if FENCE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        m = HEADING.match(line)
        if m:
            s = slug(m.group(2))
            n = counts.get(s, 0)
            counts[s] = n + 1
            out.add(s if n == 0 else f"{s}-{n}")
    for m in re.finditer(r'<a (?:name|id)="([^"]+)"', page.read_text(encoding="utf-8")):
        out.add(m.group(1))
    return out


def strip_code(text: str) -> str:
    """Text with fenced blocks and inline code removed (links inside code are not links)."""
    out, in_fence = [], False
    for line in text.splitlines():
        if FENCE.match(line):
            in_fence = not in_fence
            out.append("")
            continue
        out.append("" if in_fence else re.sub(r"`[^`]*`", "", line))
    return "\n".join(out)


def check_links(page: Path, res: Result) -> None:
    text = strip_code(page.read_text(encoding="utf-8"))
    for m in list(LINK.finditer(text)) + list(IMAGE.finditer(text)):
        target = m.group(1)
        if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith("//"):
            continue
        if PLACEHOLDER.search(target):
            continue
        path_part, _, frag = target.partition("#")
        dest = page if not path_part else (page.parent / path_part).resolve()
        line = text[: m.start()].count("\n") + 1
        where = f"{rel(page)}:{line}"
        if not dest.exists():
            res.fail(f"{where}: broken link {target}")
            continue
        if frag and dest.suffix == ".md" and frag not in anchors(dest):
            res.fail(f"{where}: missing anchor #{frag} in {rel(dest)}")


def check_dashes(path: Path, res: Result) -> None:
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        for ch, name in DASHES.items():
            if ch in line:
                res.fail(f"{rel(path)}:{n}: {name} character")


def syntax_ok(block: Block) -> str | None:
    code = PLACEHOLDER.sub("1", block.code)
    if block.lang in SHELL:
        p = subprocess.run(["bash", "-n"], input=code, text=True, capture_output=True)
        return None if p.returncode == 0 else p.stderr.strip()
    if block.lang == "python":
        try:
            ast.parse(code)
        except SyntaxError as e:
            return str(e)
        return None
    return None


def core_available() -> tuple[bool, str]:
    try:
        import queuetruth._core  # noqa: F401
    except Exception as e:  # pragma: no cover - environment dependent
        return False, f"queuetruth._core not importable ({type(e).__name__}: {e}); run `make develop`"
    return True, ""


def run_env() -> dict[str, str]:
    env = dict(os.environ)
    bindir = str(Path(sys.executable).parent)
    env["PATH"] = bindir + os.pathsep + env.get("PATH", "")
    env["QT_SRC"] = str(ROOT)
    env["QT_FIXTURES"] = str(ROOT / "tests" / "fixtures")
    env.setdefault("PYTHONNOUSERSITE", "1")
    env.pop("QT_API_KEY", None)
    return env


def run_page(page: Path, blocks: list[Block], res: Result, keep: bool) -> None:
    runnable = [b for b in blocks if b.mode == "run"]
    if not runnable:
        return
    tmp = Path(tempfile.mkdtemp(prefix="qt-docs-"))
    env = run_env()
    print(f"---- {rel(page)}: {len(runnable)} runnable block(s) in {tmp}", flush=True)
    for b in runnable:
        where = f"{rel(page)}:{b.line}"
        if PLACEHOLDER.search(b.code):
            res.fail(f"{where}: runnable block contains a placeholder")
            continue
        m = re.search(r"exit=(\d+)", b.arg)
        want = int(m.group(1)) if m else 0
        if b.lang in SHELL:
            cmd = ["bash", "-euo", "pipefail", "-c", b.code]
        elif b.lang == "python":
            cmd = [sys.executable, "-c", b.code]
        else:
            res.fail(f"{where}: runnable block with unsupported language '{b.lang}'")
            continue
        t0 = time.monotonic()
        try:
            p = subprocess.run(cmd, cwd=tmp, env=env, text=True, capture_output=True, timeout=BLOCK_TIMEOUT_S)
        except subprocess.TimeoutExpired:
            res.fail(f"{where}: timed out after {BLOCK_TIMEOUT_S} s")
            break
        dt = time.monotonic() - t0
        if p.returncode != want:
            tail = "\n".join((p.stdout + p.stderr).strip().splitlines()[-25:])
            res.fail(f"{where}: exit {p.returncode} (expected {want}) after {dt:.1f} s\n{tail}")
            break
        res.ok(f"{where} ({dt:.1f} s)")
    if not keep:
        subprocess.run(["rm", "-rf", str(tmp)], check=False)


def nav_pages(cfg: Path) -> list[str]:
    pages: list[str] = []
    in_nav = False
    for line in cfg.read_text(encoding="utf-8").splitlines():
        if re.match(r"^nav:\s*$", line):
            in_nav = True
            continue
        if in_nav and re.match(r"^\S", line):
            break
        if in_nav:
            m = re.search(r":\s*([\w./-]+\.md)\s*(#.*)?$", line) or re.search(r"^\s*-\s*([\w./-]+\.md)\s*$", line)
            if m:
                pages.append(m.group(1))
    return pages


def check_nav(res: Result) -> None:
    cfg = DOCS / "mkdocs.yml"
    if not cfg.exists():
        res.fail("docs/mkdocs.yml missing")
        return
    listed = nav_pages(cfg)
    for p in listed:
        if not (DOCS / p).exists():
            res.fail(f"docs/mkdocs.yml: nav page {p} does not exist")
    for page in sorted(DOCS.rglob("*.md")):
        r = page.relative_to(DOCS).as_posix()
        if r.startswith("launch/") or r in listed:
            continue
        res.fail(f"docs/{r}: not in docs/mkdocs.yml nav")


def check_generated(res: Result, have_core: bool, why: str) -> None:
    if not have_core:
        res.skip(f"generated reference check: {why}")
        return
    p = subprocess.run([sys.executable, str(DOCS / "gen_reference.py"), "--check"], text=True, capture_output=True)
    if p.returncode != 0:
        res.fail("docs/reference is stale; run `python docs/gen_reference.py`\n" + (p.stdout + p.stderr).strip())
    else:
        res.ok("generated reference pages are current")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--page", action="append", default=[], help="check only these pages (repeatable)")
    ap.add_argument("--no-run", action="store_true", help="do not execute runnable blocks")
    ap.add_argument("--require-core", action="store_true", help="fail instead of skipping without the extension")
    ap.add_argument("--keep-tmp", action="store_true", help="keep the per-page temporary directories")
    a = ap.parse_args(argv)

    res = Result()
    have_core, why = core_available()
    if not have_core and a.require_core:
        res.fail(why)
    pages = [Path(p).resolve() for p in a.page] or sorted(DOCS.rglob("*.md"))
    readme = EXAMPLES / "README.md"
    if not a.page and readme.exists():
        pages.append(readme)

    for page in pages:
        check_links(page, res)
        check_dashes(page, res)
        blocks = parse_blocks(page)
        for b in blocks:
            if b.mode == "skip" or (b.mode == "run" and (a.no_run or not have_core)):
                err = syntax_ok(b)
                if err:
                    res.fail(f"{rel(page)}:{b.line}: syntax error in {b.lang} block: {err}")
        if a.no_run:
            continue
        if not have_core:
            if any(b.mode == "run" for b in blocks):
                res.skip(f"{rel(page)}: runnable blocks ({why})")
            continue
        run_page(page, blocks, res, a.keep_tmp)

    if not a.page:
        for path in sorted(EXAMPLES.rglob("*")) if EXAMPLES.exists() else []:
            if path.is_file() and path.suffix in {".py", ".md", ".ipynb", ".sh"}:
                check_dashes(path, res)
        for path in [DOCS / "check_docs.py", DOCS / "gen_reference.py"]:
            if path.exists():
                check_dashes(path, res)
        check_nav(res)
        check_generated(res, have_core, why)

    print(f"\n{res.passed} passed, {len(res.skips)} skipped, {len(res.failures)} failed")
    return 1 if res.failures else 0


if __name__ == "__main__":
    sys.exit(main())
