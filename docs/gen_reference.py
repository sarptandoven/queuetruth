def schema_fields(schema: dict[str, Any]) -> str:
    props = schema.get("properties", {})
    req = set(schema.get("required", []))
    if not props:
        return "(none)"
    return ", ".join(f"`{k}`" + ("" if k in req else "?") for k in props)


def gen_mcp() -> str:
    from queuetruth.mcp.metrics import METRICS
    from queuetruth.mcp.tools import TOOLS, input_schema, output_schema

    out = [
        GENERATED,
        "",
        MCP_INTRO,
        "| Tool | Mode | Input (`?` = optional) | Output schema | Description |",
        "|---|---|---|---|---|",
    ]
    for t in TOOLS:
        mode = "local" if t.local else ("remote, `--allow-submit`" if t.submit else "remote")
        osch = output_schema(t)
        oname = osch.get("title", t.output)
        out.append(
            f"| `{t.name}` | {mode} | {schema_fields(input_schema(t))} | `{md_escape(str(oname))}` | "
            f"{md_escape(t.description)} |"
        )
    out += [
        "",
        "## Metric glossary (`qt_explain_metric`)",
        "",
        "`qt_explain_metric` returns `{name, definition, formula, proper, notes}` from this static table. "
        "`proper` is true only for strictly proper scoring rules.",
        "",
        "| Name | Definition | Formula | Proper |",
        "|---|---|---|---|",
    ]
    for name, mexp in METRICS.items():
        out.append(
            f"| `{name}` | {md_escape(mexp.definition)} | `{md_escape(mexp.formula)}` | "
            f"{'yes' if mexp.proper else 'no'} |"
        )
    return "\n".join(out).rstrip() + "\n"


