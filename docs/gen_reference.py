HTTP_INTRO = """# HTTP API reference

The self-hosted service (`queuetruth-service`) exposes `/v1`. This page is generated from `service/openapi.json`,
which the service exports (`make openapi`) and a test keeps current. The service also serves it at
`GET /v1/openapi.json`. To run the service, see [Self-host the service](../how-to/self-host-the-service.md).

## Conventions

- **Authentication.** `Authorization: Bearer <key>`, or HTTP Basic with the key as user name and an empty password.
  Keys have scopes `read`, `write` and `admin` (each includes the previous ones).
- **Idempotency.** Every POST accepts `Idempotency-Key`; endpoints marked "required" below reject a POST without it.
  The same key with the same body replays the stored response; the same key with a different body is 422
  (`idempotency-key-reused`); a request with the same key still in flight is 409 (`idempotency-in-flight`).
- **Errors** are RFC 9457 `application/problem+json` documents (`qt.problem`): `type`, `title`, `status`,
  `detail`, `code`, `request_id`, and `errors[]` for validation errors. An unknown id and another tenant's id both
  give 404, never 403. Every response carries `X-Request-Id`.
- **Lists** take `?limit=` (1 to 200, default 50) and `&starting_after=<id>` and return `qt.page`
  (`data`, `has_more`, `next_cursor`).
- **Ids** are `<prefix>_<26-character ULID>`: `ten_`, `key_`, `up_`, `ds_`, `job_`, `rp_`, `cal_`, `sc_`, `rpt_`,
  `del_`.
- **Times** in service documents are RFC 3339 UTC strings; inside analysis documents they are integer
  nanoseconds.
- **Specs** are the same objects as in the CLI and Python API, except that datasets and files are referenced by
  `dataset_id`, `upload_id` or `job_file`, and `out` must be null (the worker picks a private directory).
- **Rate limits** are per key; responses carry `RateLimit-Policy` and `RateLimit` headers (draft-based), and 429
  responses carry `Retry-After`.
- **Job flow.** Estimate (`POST /v1/<kind>/estimate`), submit (`POST /v1/<kind>`, 202 with `Location` of the job),
  poll `GET /v1/jobs/{id}`, list files (`GET /v1/jobs/{id}/files`, presigned URLs valid at most 15 minutes),
  download. The Python client (`queuetruth.client.Client`) and `queuetruth jobs ...` do this with automatic
  idempotency keys and sha256-verified, resumable downloads.
"""


def ref_name(schema: dict[str, Any] | None) -> str:
    if not schema:
        return ""
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " or ".join(filter(None, (ref_name(s) for s in schema["anyOf"])))
    if schema.get("type") == "array":
        return f"array of {ref_name(schema.get('items')) or schema['items'].get('type', '')}"
    return schema.get("format") or schema.get("type", "")


def gen_http() -> str:
    spec = json.loads((ROOT / "service" / "openapi.json").read_text(encoding="utf-8"))
    groups: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path, ops in spec["paths"].items():
        seg = path.split("/")[2] if len(path.split("/")) > 2 else path
        for method, op in ops.items():
            groups.setdefault(seg, []).append((method.upper(), path, op))
    out = [GENERATED, "", HTTP_INTRO, f"OpenAPI `{spec['openapi']}`, API version `{spec['info']['version']}`.", ""]
    out += ["## Endpoints", ""]
    order = {"GET": 0, "POST": 1, "PUT": 2, "DELETE": 3}
    for seg in sorted(groups):
        out += [f"### `/v1/{seg}`" if not seg.startswith("/") else f"### `{seg}`", ""]
        out += [
            "| Method | Path | Summary | Auth | Idempotency-Key | Request body | Success response | Status codes |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for method, path, op in sorted(groups[seg], key=lambda r: (r[1], order.get(r[0], 9))):
            auth = "API key" if op.get("security") else ("signed URL" if "_store" in path else "none")
            idem = ""
            for p in op.get("parameters", []):
                if p.get("in") == "header" and p.get("name") == "Idempotency-Key":
                    idem = "required" if p.get("required") else "optional"
            body = ""
            rb = op.get("requestBody", {}).get("content", {})
            for ctype, c in rb.items():
                body = ref_name(c.get("schema")) or ctype
            codes = sorted(op.get("responses", {}))
            ok = [c for c in codes if c.startswith("2") or c.startswith("3")]
            resp = ""
            for c in ok:
                content = op["responses"][c].get("content", {})
                for _, cc in content.items():
                    resp = ref_name(cc.get("schema"))
                    break
                if resp:
                    break
            if not resp and ok:
                resp = md_escape(op["responses"][ok[0]].get("description", ""))
            out.append(
                f"| {method} | `{path}` | {md_escape(op.get('summary', ''))} | {auth} | {idem} | {body} | {resp} | "
                f"{', '.join(codes)} |"
            )
        out.append("")
        for method, path, op in sorted(groups[seg], key=lambda r: (r[1], order.get(r[0], 9))):
            params = [p for p in op.get("parameters", []) if p.get("in") in {"query", "path"}]
            desc = md_escape(op.get("description", ""))
            if not params and not desc:
                continue
            line = f"- `{method} {path}`: {desc}"
            if params:
                ps = ", ".join(f"`{p['name']}` ({p['in']}{', required' if p.get('required') else ''})" for p in params)
                line += f" Parameters: {ps}."
            out.append(line)
        out.append("")
    schemas = spec.get("components", {}).get("schemas", {})
    out += [
        "## Component schemas",
        "",
        "Request and response bodies are defined in `components.schemas` of `service/openapi.json`. The analysis "
        "documents (`ReplaySummary`, `CalibrationResult`, `ScorecardSummary`, ...) are the same documents as in "
        "[Schemas](schemas.md).",
        "",
        ", ".join(f"`{n}`" for n in sorted(schemas)),
        "",
    ]
    return "\n".join(out).rstrip() + "\n"


