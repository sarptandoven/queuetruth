"""Generate the reference pages under docs/reference/ from the code.

Usage:
    uv run --frozen --no-sync python docs/gen_reference.py           # write the pages
    uv run --frozen --no-sync python docs/gen_reference.py --check   # exit 1 if any page would change

Sources (nothing is hand-copied):
- reference/cli.md: the clap grammar, through `queuetruth._core.cli_parse([... , "--help"])` for every visible
  command and subcommand.
- reference/python-api.md: `inspect` over `queuetruth` (top-level names) and the `__all__` of its public modules.
- reference/http-api.md: service/openapi.json.
- reference/mcp.md: `queuetruth.mcp.tools.TOOLS` and `queuetruth.mcp.metrics.METRICS`.
- reference/schemas.md: schemas/json/*.schema.json and schemas/arrow/*.json.

The conventions paragraphs at the top of each page are text constants in this file. Needs the compiled extension.
"""

from __future__ import annotations

import argparse
import importlib
import inspect
import json
import re
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "docs" / "reference"
GENERATED = "<!-- Generated by docs/gen_reference.py from the code. Do not edit by hand; rerun the script. -->"


def md_escape(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ").strip()


def first_para(doc: str | None) -> str:
    if not doc:
        return ""
    para = inspect.cleandoc(doc).split("\n\n")[0]
    return " ".join(line.strip() for line in para.splitlines())


# ---- CLI -----------------------------------------------------------------------------------------------------------

CLI_INTRO = """# CLI reference

The console script `queuetruth` parses its arguments with the same clap grammar as the standalone binary
`queuetruth-core`. Native commands run in Rust; Python and hybrid commands run in the `queuetruth` package. Each
section below is the command's own `--help` text.

## Conventions

- Global flags work before or after the subcommand: `--format human|json` (alias `--output-format`),
  `--log-level error|warn|info|debug` (default `warn`), `--threads N` (outputs never depend on it), `--seed N`,
  `--quiet`.
- Durations accept `250us`, `100ms`, `1s`, `10s`, `1m`, `5m` or an integer number of nanoseconds. Lists are
  comma-separated.
- Enum values use hyphens on the command line where the spec field uses underscores (`no-partial` is
  `no_partial`, `exchange-ack` is `exchange_ack`, `tardis-l2` is `tardis_l2`, `l2-npz` is `l2_npz`).
- Every flag maps to a field of the command's spec (see [Schemas](schemas.md)); SPEC section 4.4 lists the
  irregular mappings such as `--data` to `dataset.path` and `--latency F,D,G` to
  `latency.{feed_ns,decision_ns,gateway_ns}`.
- Exit codes: `0` success; `1` the command ran but a gate you asked for failed (`--strict`, `--fail-*`, referee
  tolerance, scorecard gates, `doctor` problems); `2` any error. With `--format json` exactly one JSON document goes
  to stdout: the summary on exit 0 or 1, a `qt.error` document on exit 2 (see [Error codes](errors.md)). Logs,
  warnings and progress go to stderr.
- Human output is answer-first: `zoo` prints the leaderboard of fill-rate bias by horizon (sorted at
  `--sort-horizon`, default 60 s) and one plain sentence per model; `score` a `RESULT:` line, the equivalence result,
  order counts, gate status and the 2x2 table (`--verbose` for every statistic); `calibrate` and `calibrate-live` the
  fitted value, the held-out comparison with the default and a trust verdict; `why` the order, its event table and a
  one-sentence conclusion. The full document is always in the output directory and in `--format json`.
- `queuetruth-core` runs the native commands; Python-only commands exit 2 with `QT-USAGE-001` there.
- Environment: `QT_API_URL` (default `http://127.0.0.1:8080`) and `QT_API_KEY` for `jobs` and remote MCP;
  `QT_MCP_ROOT` for local MCP tools.
"""


def cli_help(path: list[str]) -> str:
    from queuetruth import _core

    try:
        _core.cli_parse(["queuetruth", *path, "--help"])
    except Exception as e:  # CliExit carries (code, text, to_stderr)
        text = getattr(e, "text", None)
        if text is None and len(e.args) >= 2:
            text = e.args[1]
        if text is None:
            raise
        return str(text).rstrip() + "\n"
    raise RuntimeError(f"--help did not exit for {path}")


def subcommands(help_text: str) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    in_cmds = False
    for line in help_text.splitlines():
        if line.strip() == "Commands:":
            in_cmds = True
            continue
        if in_cmds:
            if not line.strip() or not line.startswith("  "):
                break
            m = re.match(r"^\s{2}(\S+)\s+(.*)$", line)
            if m and m.group(1) != "help":
                out.append((m.group(1), m.group(2).strip()))
    return out


def walk_cli() -> list[tuple[list[str], str, str]]:
    """(path, about, help) for every visible command, depth first, in help order."""
    rows: list[tuple[list[str], str, str]] = []

    def visit(path: list[str], about: str) -> None:
        text = cli_help(path)
        if path:
            rows.append((path, about, text))
        for name, sub_about in subcommands(text):
            visit([*path, name], sub_about)

    visit([], "")
    return rows


def gen_cli() -> str:
    rows = walk_cli()
    out = [GENERATED, "", CLI_INTRO, "## Command index", "", "| Command | What it does |", "|---|---|"]
    for path, about, _ in rows:
        name = "queuetruth " + " ".join(path)
        out.append(f"| [`{name}`](#{name.replace(' ', '-')}) | {md_escape(about)} |")
    out.append("")
    for path, _, text in rows:
        out += [f"## queuetruth {' '.join(path)}", "", "```text", text.rstrip(), "```", ""]
    return "\n".join(out).rstrip() + "\n"


