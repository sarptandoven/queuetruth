PY_INTRO = """# Python API reference

`import queuetruth as qt`. Every analysis function takes a spec (a Pydantic model from `qt.schemas` or a plain
dict, validated; unknown fields are an error) and returns the Pydantic summary model of the same JSON document the
CLI prints. Long operations release the GIL inside the extension. Tables are `pyarrow.Table`; where a table is an
input, any object implementing `__arrow_c_stream__` works (Polars, DuckDB results, pandas through pyarrow). Every
`QT-*` error raises `qt.QtError` (`.code`, `.message`, `.hint`); HTTP API errors raise `qt.QtApiError` (code
`QT-REMOTE-001`, `.problem`).

Names marked **SPEC 4.3** are the binding public API of v0.1 (SemVer applies to them). Other exported names are
listed because their modules export them, but they may change between minor versions. `queuetruth._core` is
internal.

Spec and summary models live in `queuetruth.schemas` and are documented field by field in [Schemas](schemas.md).
"""

PY_MODULES = ["stats", "eval", "model", "live", "score", "export", "report", "client"]


def spec43_names() -> set[str]:
    text = (ROOT / "docs" / "design" / "spec.md").read_text(encoding="utf-8")
    m = re.search(r"^### 4\.3 .*?(?=^### 4\.4 )", text, flags=re.S | re.M)
    body = m.group(0) if m else ""
    return set(re.findall(r"\b([A-Za-z_][A-Za-z0-9_]*)\s*\(", body)) | set(re.findall(r"qt\.([A-Za-z_]\w*)", body))


def signature(obj: Any) -> str:
    try:
        sig = str(inspect.signature(obj))
    except (TypeError, ValueError):
        return "(...)"
    return sig.replace("'", "")


def describe(name: str, obj: Any, binding: set[str]) -> list[str]:
    tag = " **SPEC 4.3**" if name in binding else ""
    if inspect.isclass(obj):
        lines = [f"### `{name}`{tag}", "", "```python", f"class {name}{signature(obj)}", "```", ""]
        doc = first_para(obj.__doc__)
        if doc:
            lines += [doc, ""]
        methods = [
            (n, f)
            for n, f in inspect.getmembers(obj)
            if not n.startswith("_")
            and (inspect.isfunction(f) or inspect.ismethod(f))
            and f.__qualname__.startswith(obj.__name__)
        ]
        if methods:
            lines += ["| Method | Signature | Description |", "|---|---|---|"]
            for n, f in methods:
                lines.append(f"| `{n}` | `{md_escape(signature(f))}` | {md_escape(first_para(f.__doc__))} |")
            lines.append("")
        return lines
    if callable(obj):
        lines = [f"### `{name}`{tag}", "", "```python", f"{name}{signature(obj)}", "```", ""]
        doc = first_para(obj.__doc__)
        return lines + ([doc, ""] if doc else [])
    return [f"### `{name}`", "", f"Constant: `{md_escape(repr(obj))[:200]}`", ""]


def gen_python() -> str:
    import queuetruth as qt

    binding = spec43_names()
    out = [GENERATED, "", PY_INTRO, f"Package version: `{qt.__version__}`.", "", "## `queuetruth`", ""]
    funcs = [n for n in qt.__all__ if n not in {"schemas", "__version__"}]
    for n in sorted(funcs, key=lambda x: (inspect.isclass(getattr(qt, x)), x.lower())):
        out += describe(n, getattr(qt, n), binding)
    for mod in PY_MODULES:
        m = importlib.import_module(f"queuetruth.{mod}")
        out += [f"## `queuetruth.{mod}`", ""]
        doc = first_para(m.__doc__)
        if doc:
            out += [doc, ""]
        names = list(getattr(m, "__all__", []))
        rows = []
        consts = []
        for n in sorted(names, key=str.lower):
            obj = getattr(m, n, None)
            if obj is None:
                continue
            if inspect.isclass(obj) or callable(obj):
                kind = "class" if inspect.isclass(obj) else "function"
                tag = "SPEC 4.3" if n in binding else ""
                sig = "" if inspect.isclass(obj) else md_escape(signature(obj))
                rows.append(
                    f"| `{n}` | {kind} | {tag} | `{sig}` | {md_escape(first_para(obj.__doc__))} |"
                    if sig
                    else f"| `{n}` | {kind} | {tag} | | {md_escape(first_para(obj.__doc__))} |"
                )
            else:
                consts.append(n)
        if rows:
            out += ["| Name | Kind | Binding | Signature | Description |", "|---|---|---|---|---|", *rows, ""]
        if consts:
            out += ["Constants: " + ", ".join(f"`{c}`" for c in consts) + ".", ""]
    return "\n".join(out).rstrip() + "\n"


