"""Python mirror of `qt_types` randomness (SPEC 3.1): splitmix64, stable_seed and xoshiro256**.

Written independently of `queuetruth.stats.stable_seed`; `test_rng_parity.py` checks both against
`schemas/rng_kat.json` (generated by the Rust implementation).
"""

from __future__ import annotations

from collections.abc import Sequence

M64 = 0xFFFFFFFFFFFFFFFF
GAMMA = 0x9E3779B97F4A7C15


def _rotl(x: int, k: int) -> int:
    return ((x << k) | (x >> (64 - k))) & M64


def splitmix64(x: int) -> int:
    """`z = x + gamma; z = (z ^ z >> 30) * C1; z = (z ^ z >> 27) * C2; z ^ z >> 31` (mod 2^64)."""
    z = (x + GAMMA) & M64
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M64
    return z ^ (z >> 31)


def stable_seed(run_seed: int, parts: Sequence[bytes]) -> int:
    """FNV-1a 64 over run_seed (8 LE bytes) and each part as (4 LE length bytes, bytes); then splitmix64."""
    data = bytearray(run_seed.to_bytes(8, "little"))
    for p in parts:
        data += len(p).to_bytes(4, "little")
        data += p
    h = 0xCBF29CE484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001B3) & M64
    return splitmix64(h)


class Xoshiro256StarStar:
    """xoshiro256** seeded with four successive splitmix64 outputs."""

    def __init__(self, seed: int) -> None:
        s = []
        x = seed & M64
        for _ in range(4):
            s.append(splitmix64(x))
            x = (x + GAMMA) & M64
        self.s = s

    def next_u64(self) -> int:
        """Next 64-bit output."""
        s = self.s
        result = (_rotl((s[1] * 5) & M64, 7) * 9) & M64
        t = (s[1] << 17) & M64
        s[2] ^= s[0]
        s[3] ^= s[1]
        s[1] ^= s[2]
        s[0] ^= s[3]
        s[2] ^= t
        s[3] = _rotl(s[3], 45)
        return result

    def next_f64(self) -> float:
        """Uniform in [0, 1): `(next_u64() >> 11) * 2^-53`."""
        return (self.next_u64() >> 11) * (1.0 / (1 << 53))

    def range_inclusive(self, lo: int, hi: int) -> int:
        """`lo + next_u64() % (hi - lo + 1)`; full range returns next_u64(); hi < lo returns lo without drawing."""
        if hi < lo:
            return lo
        span = (hi - lo + 1) & M64
        x = self.next_u64()
        return x if span == 0 else lo + x % span
