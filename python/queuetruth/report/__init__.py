"""Static self-contained HTML report (SPEC 4.3 `queuetruth.report`, 5.9).

`render(spec)` reads the output directories in `spec.inputs`, renders every section whose input exists, in the
SPEC 5.9 order, and writes one HTML file: inline CSS and server-rendered inline SVG, no external requests, complete
without JavaScript (an optional inline script only adds copy buttons), light and dark themes via
`prefers-color-scheme`, a data-table fallback for every chart. The bytes are a pure function of the inputs and the
spec: no generation time, hostname or absolute path is written. Pages larger than 10 MB are re-rendered in compact
mode (bulky data tables dropped).
"""

from __future__ import annotations

import hashlib
from collections.abc import Callable
from pathlib import Path
from typing import Any

from pydantic import ValidationError

from queuetruth._version import __version__
from queuetruth.errors import QtError
from queuetruth.eval.leaderboard import DEFAULT_SORT_HORIZON_NS
from queuetruth.report.ctx import Ctx
from queuetruth.report.load import load_inputs
from queuetruth.report.page import Raw, shell
from queuetruth.report.sections_models import calibration, learned_model, zoo
from queuetruth.report.sections_referee import referee
from queuetruth.report.sections_score import (
    data_quality,
    discordance,
    header,
    markouts,
    position,
    time_to_fill,
    two_by_two,
    verdict,
)
from queuetruth.report.why import config, why_section
from queuetruth.schemas.models import ReportSummary
from queuetruth.schemas.specs import ReportSpec

MAX_BYTES = 10 * 1024 * 1024

#: (section id, table-of-contents label, builder) in SPEC 5.9 order; the header is always present.
SECTIONS: list[tuple[str, str, Callable[[Ctx], Raw | None]]] = [
    ("verdict", "Verdict", verdict),
    ("data_quality", "Data quality", data_quality),
    ("two_by_two", "2×2 and bias", two_by_two),
    ("discordance", "Discordance", discordance),
    ("markouts", "Markouts", markouts),
    ("time_to_fill", "Time to fill", time_to_fill),
    ("position", "Position", position),
    ("zoo", "Zoo", zoo),
    ("calibration", "Calibration", calibration),
    ("learned_model", "Learned model", learned_model),
    ("referee", "Referee", referee),
    ("why", "Why traces", why_section),
    ("config", "Config and hashes", config),
]


def _build(ctx: Ctx) -> tuple[str, list[str]]:
    rendered: list[tuple[str, str, str]] = []
    for sid, label, fn in SECTIONS:
        html = fn(ctx)
        if html:
            rendered.append((sid, label, html))
    head = header(ctx)
    toc = "".join(f'<a href="#{sid}">{label}</a>' for sid, label, _ in rendered)
    nav = f'<nav class="toc" aria-label="Sections">{toc}</nav>'
    footer = (
        f"<footer>Generated by queuetruth {__version__}. Deterministic output: the same inputs and spec give "
        "byte-identical HTML; no generation time is recorded. Charts are inline SVG with data tables; no network "
        "requests are made.</footer>"
    )
    body = "\n".join([head, nav, *(h for _, _, h in rendered), footer])
    runs = ", ".join(r.label for r in ctx.inputs.runs)
    page = shell(ctx.spec.title, body, f"queuetruth report over {runs}")
    return page, ["header", *(sid for sid, _, _ in rendered)]


def _sort_horizon(sp: ReportSpec, override: int | None) -> int:
    """Leaderboard sort horizon: the keyword, else `ReportSpec.leaderboard_sort_horizon_ns` (schema 1.1; CLI
    `report --sort-horizon`), else 60 s."""
    v = override if override is not None else sp.leaderboard_sort_horizon_ns
    if v is None:
        return DEFAULT_SORT_HORIZON_NS
    if isinstance(v, bool) or not isinstance(v, int) or v <= 0:
        raise QtError("QT-CONFIG-001", f"leaderboard sort horizon must be a positive integer of ns, got {v!r}")
    return int(v)


def render(spec: ReportSpec | dict[str, Any], *, leaderboard_sort_horizon_ns: int | None = None) -> ReportSummary:
    """Renders the report of SPEC 5.9 to `spec.out` and returns its `qt.report_summary`. The zoo leaderboard is
    sorted by absolute fill-rate bias at the keyword `leaderboard_sort_horizon_ns`, else the spec field of that
    name, else 60 s."""
    try:
        sp = spec if isinstance(spec, ReportSpec) else ReportSpec.model_validate(spec)
    except ValidationError as e:
        raise QtError("QT-CONFIG-001", f"invalid ReportSpec: {e}") from e
    if not sp.out:
        raise QtError("QT-CONFIG-001", "out: the report needs an output file path", hint="--out report.html")
    hsort = _sort_horizon(sp, leaderboard_sort_horizon_ns)
    inputs = load_inputs(list(sp.inputs))
    page, sections = _build(Ctx(spec=sp, inputs=inputs, sort_horizon_ns=hsort))
    data = page.encode("utf-8")
    if len(data) > MAX_BYTES:
        page, sections = _build(Ctx(spec=sp, inputs=inputs, compact=True, sort_horizon_ns=hsort))
        data = page.encode("utf-8")
    out = Path(sp.out)
    try:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(data)
    except OSError as e:
        raise QtError("QT-INPUT-001", f"{sp.out}: cannot write report: {e}") from e
    return ReportSummary(
        inputs=list(sp.inputs),
        out=sp.out,
        sections=sections,
        bytes=len(data),
        sha256=hashlib.sha256(data).hexdigest(),
    )


__all__ = ["render"]
