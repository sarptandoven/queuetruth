"""What the venue terms allow, stated plainly (not legal advice; read on 2026-10-22 to 2026-10-24).

The prediction-market kit is software you run yourself on data you captured yourself, under your own venue account.
It reads only files you pass, makes no network calls, ships no venue data, and has no upload, hosting or publishing
path. Everything it writes is derived from your captures and stays covered by the same terms as the captures.

- **Kalshi.** The DCM Rulebook v1.29 (Rule 11.1(b)) lets members use market data "for their own internal business
  purposes" and bars distributing, selling or retransmitting it to any third party; the Developer Agreement limits
  API use to your own trading. Running this kit on your own captures for your own trading fits that. Sending your
  captures, books or scores to anyone else, hosting them, or publishing scores derived from Kalshi data needs
  Kalshi's written permission. The Developer Agreement also bars API access "for any other benchmarking or
  competitive purposes"; scoring your own simulator against your own fills is arguably part of your own trading,
  but ask Kalshi before you market anything built on it.
- **Polymarket (international).** The Terms of Use (effective 2026-08-11) bar "Capital Market Clients" (including
  market makers, proprietary trading firms and financial technology companies) and market-data distributors from
  accessing Polymarket data, on-chain data included, without a written agreement, and bar reselling or
  redistributing that data to them. If you are such a firm, you need your own agreement with Polymarket before you
  capture data to run this kit on. Retail use of your own data is not expressly barred.
- **Polymarket US.** Rulebook Rule 5.3(g) bars redistributing information received through the trading system
  without express permission. Internal use of your own captures is the participant's own business.

Do not commit, upload or share captures, ingested books or score outputs. queuetruth's own example captures are
generated by `queuetruth.pm.fixtures` (`queuetruth pm fixtures`: an exact simulated FIFO book written in the
documented message formats), and the reader tests build their messages by hand in `python/tests/pm/_helpers.py`;
markets, accounts and values are invented in both.
"""

