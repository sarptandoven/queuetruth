"""Writes crates/cli/src/operations.rs: the operation table of `queuetruth.ops.table()` as Rust rows.

`queuetruth-core run <op> --spec FILE` reads these rows to know every operation by name, to put `--out DIR` where
the runner puts it (`out_field`, with `out_name` inside), and to list the table (`run --list`). The Python table
stays the source of truth; this script copies it, and `--check` fails when the copy is stale.

    uv run --frozen --no-sync python crates/cli/gen_operations.py           # write the file
    uv run --frozen --no-sync python crates/cli/gen_operations.py --check   # exit 1 if it would change
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "src" / "operations.rs"
REPO = HERE.parent.parent


def _lit(s: str | None) -> str:
    return "None" if s is None else f"Some({json.dumps(s)})"


def generate() -> str:
    sys.path.insert(0, str(REPO / "python"))
    from queuetruth.ops.table import table
    from queuetruth.schemas.specs import SPEC_MODELS

    schema_of = {model: name for name, model in SPEC_MODELS.items()}
    rows = []
    for op in table().values():
        rows.append(
            "    OperationRow {\n"
            f"        name: {json.dumps(op.name)},\n"
            f"        description: {json.dumps(op.description)},\n"
            f"        spec_model: {json.dumps(op.spec.__name__)},\n"
            f"        spec_schema: {_lit(schema_of.get(op.spec))},\n"
            f"        out_field: {_lit(op.out_field)},\n"
            f"        out_name: {_lit(op.out_name)},\n"
            "    },\n"
        )
    return (
        "//! Generated by crates/cli/gen_operations.py from the operation table (`queuetruth.ops.table()`). Do not\n"
        "//! edit by hand; rerun the script (`make generate`).\n\n"
        "/// One operation of the table.\n"
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize)]\n"
        "pub struct OperationRow {\n"
        "    /// The runner's name (`replay`, `shadows`).\n"
        "    pub name: &'static str,\n"
        "    /// One line.\n"
        "    pub description: &'static str,\n"
        "    /// The name of its spec model (`ReplaySpec`), as validation errors name it.\n"
        "    pub spec_model: &'static str,\n"
        "    /// The published JSON Schema of its spec (`qt.replay_spec`); None for a verb's own spec.\n"
        "    pub spec_schema: Option<&'static str>,\n"
        "    /// The spec field that names the output location; None when it writes no files.\n"
        "    pub out_field: Option<&'static str>,\n"
        "    /// The file or directory put inside an output directory given with `--out`; None: the directory.\n"
        "    pub out_name: Option<&'static str>,\n"
        "}\n\n"
        "/// Every operation, sorted by name.\n"
        f"pub const OPERATIONS: &[OperationRow] = &[\n{''.join(rows)}];\n"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the file is out of date (writes nothing)")
    a = ap.parse_args(argv)
    text = generate()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if a.check:
        if text != current:
            print(f"{OUT.relative_to(REPO)} is stale; run python crates/cli/gen_operations.py", file=sys.stderr)
            return 1
        return 0
    if text != current:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
